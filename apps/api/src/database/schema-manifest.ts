export async function verifySchema<TTable extends string>(
  client: Client,
  manifest: SchemaManifest<TTable>,
): Promise<SchemaVerification> {
  const diffs: string[] = [];
  const expectedTables = Object.keys(manifest.tables) as TTable[];

  // Columns
  const colRows = await queryRows<ColumnRow>(
    client,
    `SELECT c.table_name, c.column_name, c.data_type, c.udt_name,
            c.character_maximum_length, c.is_nullable, c.column_default,
            COALESCE(a.attidentity, '') AS attidentity
     FROM information_schema.columns c
     JOIN pg_class cls ON cls.relname = c.table_name
     JOIN pg_namespace n
       ON n.oid = cls.relnamespace AND n.nspname = c.table_schema
     JOIN pg_attribute a
       ON a.attrelid = cls.oid AND a.attname = c.column_name
     WHERE c.table_schema = $1 AND c.table_name = ANY($2::text[])
       AND a.attnum > 0 AND NOT a.attisdropped
     ORDER BY c.table_name, c.ordinal_position`,
    [manifest.schema, [...expectedTables]],
  );

  const actualColumns = buildMap<string, ColumnSpec>();
  const actualIdentity = new Map<string, string>();
  for (const row of colRows) {
    pushToMap(actualColumns, row.table_name, {
      name: row.column_name,
      dataType: row.data_type,
      udtName: row.udt_name,
      charMaxLength: row.character_maximum_length,
      isNullable: row.is_nullable === 'YES',
      columnDefault: normalizeDefault(row.column_default),
    });
    actualIdentity.set(`${row.table_name}.${row.column_name}`, row.attidentity);
  }

  for (const table of expectedTables) {
    const expected = manifest.tables[table];
    if (expected === undefined) continue;
    const actualList = actualColumns.get(table) ?? [];

    const actualByName = new Map(actualList.map((c) => [c.name, c]));
    for (const expectedCol of expected.columns) {
      const actualCol = actualByName.get(expectedCol.name);
      if (actualCol === undefined) {
        diffs.push(`${table}.${expectedCol.name}: column is missing`);
        continue;
      }
      if (actualCol.dataType !== expectedCol.dataType) {
        diffs.push(
          `${table}.${expectedCol.name}: expected data_type ${expectedCol.dataType}, got ${actualCol.dataType}`,
        );
      }
      if (actualCol.udtName !== expectedCol.udtName) {
        diffs.push(
          `${table}.${expectedCol.name}: expected udt_name ${expectedCol.udtName}, got ${actualCol.udtName}`,
        );
      }
      if (actualCol.charMaxLength !== expectedCol.charMaxLength) {
        diffs.push(
          `${table}.${expectedCol.name}: expected char_max_length ${expectedCol.charMaxLength}, got ${actualCol.charMaxLength}`,
        );
      }
      if (actualCol.isNullable !== expectedCol.isNullable) {
        diffs.push(
          `${table}.${expectedCol.name}: expected nullable ${expectedCol.isNullable}, got ${actualCol.isNullable}`,
        );
      }
      // Identity columns: PG omits the nextval default from
      // information_schema.columns.column_default; identity is encoded in
      // pg_attribute.attidentity. When the manifest declares an identity
      // column we MUST see columnDefault = NULL AND attidentity = 'd'
      // (BY DEFAULT). For non-identity columns we still compare the
      // columnDefault string as before.
      if (expectedCol.identity !== undefined) {
        if (actualCol.columnDefault !== null) {
          diffs.push(
            `${table}.${expectedCol.name}: expected identity column (default null), got column_default ${actualCol.columnDefault ?? 'null'}`,
          );
        }
        const actualAttidentity = actualIdentity.get(`${table}.${expectedCol.name}`) ?? '';
        if (actualAttidentity !== 'd') {
          diffs.push(
            `${table}.${expectedCol.name}: expected attidentity='d' (GENERATED BY DEFAULT AS IDENTITY), got '${actualAttidentity}'`,
          );
        }
      } else if (actualCol.columnDefault !== expectedCol.columnDefault) {
        diffs.push(
          `${table}.${expectedCol.name}: expected default ${expectedCol.columnDefault ?? 'null'}, got ${actualCol.columnDefault ?? 'null'}`,
        );
      }
    }
    const expectedNames = new Set(expected.columns.map((c) => c.name));
    for (const actualCol of actualList) {
      if (!expectedNames.has(actualCol.name)) {
        diffs.push(`${table}.${actualCol.name}: unexpected extra column`);
      }
    }
  }

  // Constraints (PK, unique, FK, check) via pg_get_constraintdef.
  const conRows = await queryRows<ConstraintRow>(
    client,
    `SELECT cls.relname AS table_name,
            con.conname AS constraint_name,
            con.contype AS constraint_type,
            pg_get_constraintdef(con.oid) AS definition
     FROM pg_constraint con
     JOIN pg_class cls ON cls.oid = con.conrelid
     JOIN pg_namespace ns ON ns.oid = cls.relnamespace
     WHERE ns.nspname = $1 AND cls.relname = ANY($2::text[])
       AND con.contype IN ('p', 'u', 'f', 'c')`,
    [manifest.schema, [...expectedTables]],
  );

  const actualConstraints = buildMap<string, string>();
  for (const row of conRows) {
    const def = row.definition ?? '';
    pushToMap(actualConstraints, row.table_name, def);
  }

  for (const table of expectedTables) {
    const expected = manifest.tables[table];
    if (expected === undefined) continue;
    const rawDefs = actualConstraints.get(table) ?? [];

    const pkDefs: string[] = [];
    const uniqueDefs: string[] = [];
    const fkDefs: string[] = [];
    const checkDefs: string[] = [];

    for (const def of rawDefs) {
      const normalized = collapseWhitespace(def).toLowerCase();
      if (normalized.startsWith('primary key')) pkDefs.push(normalizePrimaryKey(def));
      else if (normalized.startsWith('unique')) uniqueDefs.push(normalizeUnique(def));
      else if (normalized.startsWith('foreign key')) fkDefs.push(normalizeForeignKey(def));
      else if (normalized.startsWith('check')) checkDefs.push(normalizeCheckDefinition(def));
    }

    const expectedPk = normalizePrimaryKey(
      `PRIMARY KEY (${expected.primaryKey.columns.join(', ')})`,
    );
    if (!pkDefs.includes(expectedPk)) {
      diffs.push(`${table}: missing PRIMARY KEY (${expected.primaryKey.columns.join(', ')})`);
    }

    const expectedUniqueSet = new Set(
      expected.uniques.map((u) => normalizeUnique(`UNIQUE (${u.columns.join(', ')})`)),
    );
    for (const expectedUnique of expectedUniqueSet) {
      if (!uniqueDefs.includes(expectedUnique)) {
        diffs.push(`${table}: missing UNIQUE ${expectedUnique}`);
      }
    }
    for (const actualUnique of uniqueDefs) {
      if (!expectedUniqueSet.has(actualUnique)) {
        diffs.push(`${table}: unexpected UNIQUE ${actualUnique}`);
      }
    }

    const expectedFkSet = new Set(
      expected.foreignKeys.map((fk) =>
        normalizeForeignKey(
          `FOREIGN KEY (${fk.columns.join(', ')}) REFERENCES ${fk.referencesTable}(${fk.referencesColumns.join(', ')}) ON DELETE ${fk.deleteAction}`,
        ),
      ),
    );
    for (const expectedFk of expectedFkSet) {
      if (!fkDefs.includes(expectedFk)) {
        diffs.push(`${table}: missing FOREIGN KEY ${expectedFk}`);
      }
    }
    for (const actualFk of fkDefs) {
      if (!expectedFkSet.has(actualFk)) {
        diffs.push(`${table}: unexpected FOREIGN KEY ${actualFk}`);
      }
    }

    const expectedCheckSet = new Set(expected.checks.map((c) => c.definition));
    for (const expectedCheck of expectedCheckSet) {
      if (!checkDefs.includes(expectedCheck)) {
        diffs.push(`${table}: missing CHECK ${expectedCheck}`);
      }
    }
    for (const actualCheck of checkDefs) {
      if (!expectedCheckSet.has(actualCheck)) {
        diffs.push(`${table}: unexpected CHECK ${actualCheck}`);
      }
    }
  }

  // Indexes (explicit + implicit from PK/UNIQUE).
  const idxRows = await queryRows<IndexRow>(
    client,
    `SELECT i.relname AS index_name, t.relname AS table_name, pg_get_indexdef(i.oid) AS indexdef
     FROM pg_index ix
     JOIN pg_class i ON i.oid = ix.indexrelid
     JOIN pg_class t ON t.oid = ix.indrelid
     JOIN pg_namespace n ON n.oid = t.relnamespace
     WHERE n.nspname = $1 AND t.relname = ANY($2::text[])`,
    [manifest.schema, [...expectedTables]],
  );

  const actualIndexes = buildMap<string, IndexSpec>();
  const unparseableIndexes = buildMap<string, { name: string; definition: string }>();
  for (const row of idxRows) {
    const parsed = parseIndexDef(row.indexdef, row.table_name, row.index_name);
    if (parsed !== undefined) {
      pushToMap(actualIndexes, row.table_name, parsed);
    } else {
      pushToMap(unparseableIndexes, row.table_name, {
        name: row.index_name,
        definition: row.indexdef,
      });
    }
  }

  for (const table of expectedTables) {
    const expected = manifest.tables[table];
    if (expected === undefined) continue;
    const actualList = actualIndexes.get(table) ?? [];
    const unparseableList = unparseableIndexes.get(table) ?? [];
    const unparseableByName = new Map(unparseableList.map((u) => [u.name, u]));

    const expectedIndexSet = new Set(expected.indexes.map((i) => indexSpecKey(i)));
    const actualIndexSet = new Set(actualList.map((i) => indexSpecKey(i)));

    for (const expectedKey of expectedIndexSet) {
      if (!actualIndexSet.has(expectedKey)) {
        const expectedSpec = expected.indexes.find((i) => indexSpecKey(i) === expectedKey);
        if (expectedSpec !== undefined && unparseableByName.has(expectedSpec.name)) {
          diffs.push(`${table}: index ${expectedSpec.name} has an unparseable definition`);
        } else {
          diffs.push(`${table}: missing index ${expectedKey}`);
        }
      }
    }
    for (const actualKey of actualIndexSet) {
      if (!expectedIndexSet.has(actualKey)) {
        diffs.push(`${table}: unexpected index ${actualKey}`);
      }
    }
    for (const unparseable of unparseableList) {
      const anyExpectedWithSameName = expected.indexes.some((i) => i.name === unparseable.name);
      if (!anyExpectedWithSameName) {
        diffs.push(`${table}: unexpected unparseable index ${unparseable.name}`);
      }
    }
  }

  return {
    passed: diffs.length === 0,
    diffs,
    actualTableNames: colRows.map((r) => r.table_name).filter((v, i, a) => a.indexOf(v) === i),
  };
}

function normalizePrimaryKey(def: string): string {
  const m = /^PRIMARY\s+KEY\s*\(([^)]+)\)/i.exec(def);
  if (m === null) return collapseWhitespace(def).toLowerCase();
  return `primary key (${collapseWhitespace(m[1] ?? '').toLowerCase()})`;
}

function normalizeUnique(def: string): string {
  const m = /^UNIQUE\s*\(([^)]+)\)/i.exec(def);
  if (m === null) return collapseWhitespace(def).toLowerCase();
  return `unique (${collapseWhitespace(m[1] ?? '').toLowerCase()})`;
}

function normalizeForeignKey(def: string): string {
  let s = collapseWhitespace(def);
  s = s.replace(/^FOREIGN\s+KEY\s+/i, '');
  s = lowercase(s);
  s = stripPublicSchema(s);
  return s;
}

function indexSpecKey(spec: IndexSpec): string {
  const where = spec.where === null ? '' : ` where ${spec.where}`;
  return `${spec.unique ? 'unique ' : ''}index ${spec.name} on ${spec.table}(${spec.columns.join(', ')})${where}`;
}

function splitIndexColumns(raw: string): string[] {
  const columns: string[] = [];
  let current = '';
  let depth = 0;
  for (const ch of raw) {
    if (ch === '(') depth += 1;
    if (ch === ')') depth -= 1;
    if (ch === ',' && depth === 0) {
      columns.push(current.trim());
      current = '';
      continue;
    }
    current += ch;
  }
  if (current.trim() !== '') columns.push(current.trim());
  return columns;
}

export function parseIndexDef(def: string, table: string, name: string): IndexSpec | undefined {
  const normalized = normalizeIndexDefinition(def);

  const uniquePrefix = 'create unique index ';
  const plainPrefix = 'create index ';
  let rest: string;
  let unique = false;
  if (normalized.startsWith(uniquePrefix)) {
    unique = true;
    rest = normalized.slice(uniquePrefix.length);
  } else if (normalized.startsWith(plainPrefix)) {
    rest = normalized.slice(plainPrefix.length);
  } else {
    return undefined;
  }

  // rest: <name> on <table> using <method> (<columns>) [where <predicate>]
  const onIndex = rest.indexOf(' on ');
  if (onIndex === -1) return undefined;
  const indexName = rest.slice(0, onIndex).trim() || name;
  rest = rest.slice(onIndex + ' on '.length);

  const usingIndex = rest.indexOf(' using ');
  if (usingIndex === -1) return undefined;
  const tableName = rest.slice(0, usingIndex).trim() || table;
  rest = rest.slice(usingIndex + ' using '.length);

  // Skip the access method (e.g. btree) and find the matching '(' for the
  // column/expression list. This correctly handles functional expressions such
  // as lower(code), which contain nested parentheses.
  const colStart = rest.indexOf('(');
  if (colStart === -1) return undefined;
  let depth = 1;
  let colEnd = -1;
  for (let i = colStart + 1; i < rest.length; i += 1) {
    if (rest[i] === '(') depth += 1;
    else if (rest[i] === ')') {
      depth -= 1;
      if (depth === 0) {
        colEnd = i;
        break;
      }
    }
  }
  if (colEnd === -1) return undefined;

  const columnsRaw = rest.slice(colStart + 1, colEnd);
  const afterColumns = rest.slice(colEnd + 1).trim();
  let whereRaw: string | null = null;
  if (afterColumns.startsWith('where ')) {
    whereRaw = afterColumns.slice('where '.length).trim();
  } else if (afterColumns !== '') {
    return undefined;
  }

  return {
    name: indexName,
    table: tableName,
    columns: splitIndexColumns(columnsRaw).map((c) =>
      normalizeIndexExpression(collapseWhitespace(c).toLowerCase()),
    ),
    unique,
    where: whereRaw === null ? null : normalizeCheckDefinition(whereRaw),
  };
}
