interface ColumnRow extends Record<string, unknown> {
  table_name: string;
  column_name: string;
  data_type: string;
  udt_name: string;
  character_maximum_length: number | null;
  is_nullable: string;
  column_default: string | null;
  /**
   * `pg_attribute.attidentity`: `'d'` (BY DEFAULT IDENTITY), `'a'` (ALWAYS
   * IDENTITY) or empty string (non-identity). Always present as an empty
   * string in the projected row, never NULL, so the verifier can rely on
   * `=== 'd'` checks without nullability.
   */
  attidentity: string;
}

interface ConstraintRow extends Record<string, unknown> {
  table_name: string;
  constraint_name: string;
  constraint_type: string;
  definition: string | null;
}

interface IndexRow extends Record<string, unknown> {
  index_name: string;
  table_name: string;
  indexdef: string;
}

async function queryRows<T extends Record<string, unknown>>(
  client: Client,
  text: string,
  values?: unknown[],
): Promise<T[]> {
  const result = values
    ? await client.query<T>(text, values as never[])
    : await client.query<T>(text);
  return (result.rows as T[]) ?? [];
}

function buildMap<K, V>(): Map<K, V[]> {
  return new Map<K, V[]>();
}

function pushToMap<K, V>(map: Map<K, V[]>, key: K, value: V): void {
  const list = map.get(key);
  if (list === undefined) {
    map.set(key, [value]);
  } else {
    list.push(value);
  }
}

