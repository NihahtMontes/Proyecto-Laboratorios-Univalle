/**
 * Schema manifest and verification for the identity control-plane migration (0001).
 *
 * `verifySchema` compares the live PostgreSQL catalog (information_schema + pg_catalog)
 * against a declarative manifest. It reads no business rows and prints no secrets.
 *
 * The expected manifest for 0001 is exhaustive: every column, constraint and index on the
 * four target tables is declared. Any missing or extra object in those tables is a failure.
 */
import type { Client } from 'pg';
import { type ControlPlaneTable, type TargetTable } from './migration-plan.js';

export interface ColumnSpec {
  readonly name: string;
  readonly dataType: string;
  readonly udtName: string;
  readonly charMaxLength: number | null;
  readonly isNullable: boolean;
  readonly columnDefault: string | null;
  /**
   * Identity mode declared by `GENERATED <mode> AS IDENTITY`. When set, the
   * verifier expects `information_schema.columns.column_default = NULL`
   * (PG does not surface IDENTITY defaults in `column_default`), asserts
   * `pg_attribute.attidentity = 'd'` (BY DEFAULT) on the owning column and
   * accepts the supplemental ownership `pg_depend.deptype = 'i'`
   * (internal/identity link from sequence -> column) in addition to the
   * legacy `'a'` (auto/serial) link. Only `'BY DEFAULT'` is permitted by
   * the contract; `ALWAYS` would require a separate expectation.
   */
  readonly identity?: IdentitySpec;
}

export interface IdentitySpec {
  readonly generated: 'BY DEFAULT';
  readonly sequence: string;
}

export interface PrimaryKeySpec {
  readonly columns: readonly string[];
}

export interface UniqueSpec {
  readonly columns: readonly string[];
}

export interface ForeignKeySpec {
  readonly columns: readonly string[];
  readonly referencesTable: string;
  readonly referencesColumns: readonly string[];
  readonly deleteAction: 'RESTRICT';
}

export interface CheckSpec {
  /** Normalized CHECK expression (without the CHECK keyword and without autogenerated name). */
  readonly definition: string;
}

export interface IndexSpec {
  readonly name: string;
  readonly table: string;
  readonly columns: readonly string[];
  readonly unique: boolean;
  /** Normalized partial-index predicate, or null for a full index. */
  readonly where: string | null;
}

export interface TableManifest {
  readonly columns: readonly ColumnSpec[];
  readonly primaryKey: PrimaryKeySpec;
  readonly uniques: readonly UniqueSpec[];
  readonly foreignKeys: readonly ForeignKeySpec[];
  readonly checks: readonly CheckSpec[];
  readonly indexes: readonly IndexSpec[];
}

export interface SchemaManifest<TTable extends string = TargetTable> {
  readonly schema: string;
  readonly tables: Readonly<Record<TTable, TableManifest>>;
}

export interface SchemaVerification {
  readonly passed: boolean;
  readonly diffs: readonly string[];
  readonly actualTableNames: readonly string[];
}

