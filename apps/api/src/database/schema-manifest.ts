function collapseWhitespace(value: string): string {
  return value.trim().replace(/\s+/g, ' ');
}

function lowercase(value: string): string {
  return value.toLowerCase();
}

function stripPublicSchema(value: string): string {
  return value.replace(/\bpublic\./g, '');
}

function stripTypeCasts(value: string): string {
  return value.replace(
    /::\s*(?:text|bpchar|boolean|bigint|uuid|numeric|integer|int4|int8|smallint|decimal|real|double precision|date|time)\b/g,
    '',
  );
}

/**
 * Strip PG-18 wrapper parens around an identifier that is about to be cast:
 * `(column)::TYPE` -> `column::TYPE`. Only the `(id)::` cast shape is
 * touched; function calls like `length(column)` are intentionally left
 * alone so the expression remains semantically a function call. PG-18 emits
 * CHECK expressions with explicit wrapper parens and an implicit cast
 * around column references; this helper collapses that wrapper so the
 * downstream `stripTypeCasts` and `canonicalizeAnyArrayToIn` steps can
 * match the canonical form documented in the schema manifest. The match is
 * anchored by a lookahead for `::` so the wrapper is only removed when the
 * identifier is in a cast position; without the lookahead, `(col)` inside
 * a function call would be wrongly stripped.
 */
function stripCastWrap(value: string): string {
  let prev: string;
  do {
    prev = value;
    value = value.replace(/\(\s*([a-zA-Z_][a-zA-Z0-9_]*)\s*\)\s*(?=::)/g, '$1');
  } while (value !== prev);
  return value;
}

/**
 * Strip redundant double quotes around identifiers that PostgreSQL quotes
 * ONLY because they collide with a reserved keyword (e.g. `"position"`,
 * `"length"`). A quoted identifier `"<id>"` is collapsed to bare `<id>`
 * ONLY when its content is a simple, already-lowercase, ASCII identifier
 * matching `[a-zA-Z_][a-zA-Z0-9_]*` — i.e. one that PG could legally
 * write unquoted without changing meaning. The regex explicitly handles
 * the doubled-quote escape form `"a""b"` by recognizing a single
 * embedded `""` (and PRESERVING the whole token in that case so the
 * outer pair does not get stripped around only the inner identifier).
 *
 * Preserved (NOT weakened):
 *  - Case-sensitive identifiers: `"Position"`, `"MyColumn"`, `"ALL_CAPS"`.
 *  - Identifiers with non-identifier characters: `"my column"`,
 *    `"col-with-dash"`, `"col.with.dots"`, `"special$char"`.
 *  - Escaped-quote identifiers: `"col""name"` — the optional inner
 *    `""name` segment is captured; if present the whole match is
 *    returned untouched so the escape structure is preserved.
 *  - The empty string `""` (regex requires at least one identifier char).
 *
 * The stripper runs BEFORE `lowercase` so that a case-sensitive quoted
 * identifier (which would be lowercased to its lowercase form) keeps its
 * quotes intact, preserving the distinction between `position` (bare,
 * case-insensitive, equals `"POSITION"`, `"Position"`, etc.) and
 * `"Position"` (case-sensitive quoted — a different PG identifier).
 */
function stripRedundantDoubleQuotes(value: string): string {
  return value.replace(
    /"([a-zA-Z_][a-zA-Z0-9_]*)(?:""([a-zA-Z_][a-zA-Z0-9_]*))?"/g,
    (match, id1: string, id2?: string) => {
      if (id2 !== undefined) {
        // Escaped-quote identifier: the outer pair is NOT keyword-quoting,
        // it is structural. Preserve the whole match untouched.
        return match;
      }
      return id1 === id1.toLowerCase() ? id1 : match;
    },
  );
}

function stripOuterParentheses(value: string): string {
  let s = value.trim();
  while (s.startsWith('(') && s.endsWith(')')) {
    const inner = s.slice(1, -1).trim();
    // Stop if the inner text has unbalanced parentheses.
    let depth = 0;
    let balanced = true;
    for (const ch of inner) {
      if (ch === '(') depth += 1;
      if (ch === ')') {
        depth -= 1;
        if (depth < 0) {
          balanced = false;
          break;
        }
      }
    }
    if (!balanced || depth !== 0) break;
    s = inner;
  }
  return s;
}

/**
 * Splits `value` by `delimiter` only at the top nesting level (parentheses and
 * square brackets are tracked; string literals are skipped). Used to parse
 * expression lists and boolean chains deterministically.
 */
function splitTopLevel(value: string, delimiter: string): string[] {
  const result: string[] = [];
  let current = '';
  let depth = 0;
  let inString: string | null = null;
  const lowerDelimiter = delimiter.toLowerCase();
  let i = 0;
  while (i < value.length) {
    const ch = value[i];
    if (inString !== null) {
      current += ch;
      if (ch === inString) {
        // Doubled quote is an escaped quote inside the literal.
        if (i + 1 < value.length && value[i + 1] === inString) {
          current += value[i + 1];
          i += 2;
          continue;
        }
        inString = null;
      }
      i += 1;
      continue;
    }
    if (ch === "'" || ch === '"') {
      inString = ch;
      current += ch;
      i += 1;
      continue;
    }
    if (ch === '(' || ch === '[') {
      depth += 1;
    } else if (ch === ')' || ch === ']') {
      depth -= 1;
    }
    if (depth === 0 && value.slice(i, i + delimiter.length).toLowerCase() === lowerDelimiter) {
      result.push(current);
      current = '';
      i += delimiter.length;
      continue;
    }
    current += ch;
    i += 1;
  }
  result.push(current);
  return result;
}

/**
 * Canonicalises PostgreSQL's `x = ANY (ARRAY[...])` form back to the equivalent
 * `x IN (...)` form. Both are deterministic and preserve every value, operator
 * and column; only the textual representation is normalised.
 */
function canonicalizeAnyArrayToIn(definition: string): string {
  return definition.replace(
    /\b([a-z_][a-z0-9_$]*)\s*=\s*any\s*\(\s*array\s*\[(.+?)\]\s*\)/gi,
    (_match, expr: string, itemsRaw: string) => {
      const items = splitTopLevel(itemsRaw, ',')
        .map((item) => collapseWhitespace(item))
        .filter((item) => item !== '');
      return `${expr.toLowerCase()} in (${items.join(', ')})`;
    },
  );
}

const VARCHAR_STRING_LITERAL = /^('(?:[^']|'')*')::character varying$/;

/**
 * For a varchar column, `col IN ('a', 'b')` is rendered by PG as
 * `(col)::text = ANY ((ARRAY['a'::character varying, 'b'::character varying])::text[])`.
 * Casting an array of varchar string literals to text[] only relabels each
 * element (varchar -> text is binary-coercible), so the array is rewritten
 * to `array['a', 'b']`, which `canonicalizeAnyArrayToIn` then folds into IN.
 * The rewrite applies ONLY when every element is a plain string literal typed
 * `character varying` and the array cast is exactly `::text[]`; any other
 * element shape or cast target is left untouched (fail closed). The operator
 * (`= any`, `<> all`, ...) is never touched here.
 */
function canonicalizeVarcharLiteralArray(definition: string): string {
  return definition.replace(
    /\(\s*array\s*\[([^\]]*)\]\s*\)::text\[\]/g,
    (match, itemsRaw: string) => {
      const items = splitTopLevel(itemsRaw, ',').map((item) => collapseWhitespace(item));
      const literals: string[] = [];
      for (const item of items) {
        const literal = VARCHAR_STRING_LITERAL.exec(item);
        if (literal === null) return match;
        literals.push(literal[1]!);
      }
      return `array[${literals.join(', ')}]`;
    },
  );
}

/**
 * For a varchar column, `COALESCE(col, '')` used in a text context is
 * rendered by PG as `(coalesce(col, ''::character varying))::text`.
 * varchar -> text is a binary-coercible relabel, so this equals
 * `coalesce(col, ''::text)`. Only a bare identifier plus a single string
 * literal typed `character varying` is rewritten; bpchar (which trims on
 * cast), non-literal fallbacks and any other coalesce shape are left
 * untouched. Shared by index-expression and CHECK normalization.
 */
function canonicalizeVarcharCoalesceLiteral(expression: string): string {
  return expression.replace(
    /\(\s*coalesce\(\s*([a-zA-Z_][a-zA-Z0-9_]*)\s*,\s*('(?:[^']|'')*')::character varying\s*\)\s*\)::text\b/g,
    'coalesce($1, $2::text)',
  );
}

// ---------------------------------------------------------------------------
// Boolean-expression parser for deterministic CHECK normalisation.
//
// PostgreSQL may add redundant parentheses around OR/AND terms; the parser
// rebuilds the expression tree and re-emits it with the minimal parentheses
// required to preserve precedence. It never hides operators, columns or values.
// ---------------------------------------------------------------------------

type BooleanToken =
  | { type: 'ident'; value: string }
  | { type: 'literal'; value: string }
  | { type: 'op'; value: string }
  | { type: 'keyword'; value: string }
  | { type: 'punct'; value: string };

type BooleanExpr =
  | { type: 'or'; terms: BooleanExpr[] }
  | { type: 'and'; terms: BooleanExpr[] }
  | { type: 'not'; operand: BooleanExpr }
  | { type: 'compare'; left: BooleanExpr; op: string; right: BooleanExpr | null }
  | { type: 'in'; expr: BooleanExpr; values: BooleanExpr[] }
  | { type: 'isnull'; expr: BooleanExpr; not: boolean }
  | { type: 'ident'; value: string }
  | { type: 'literal'; value: string }
  | { type: 'func'; name: string; args: BooleanExpr[] }
  | { type: 'array'; items: BooleanExpr[] };

const BOOLEAN_KEYWORDS = new Set(['or', 'and', 'not', 'is', 'in', 'null', 'any', 'array']);

function tokenizeExpression(value: string): BooleanToken[] {
  const tokens: BooleanToken[] = [];
  let i = 0;
  while (i < value.length) {
    const ch = value[i]!;
    if (/\s/.test(ch)) {
      i += 1;
      continue;
    }
    if (ch === "'" || ch === '"') {
      let literal = ch;
      let j = i + 1;
      while (j < value.length) {
        const c = value[j]!;
        literal += c;
        if (c === ch) {
          if (value[j + 1] === ch) {
            literal += ch;
            j += 2;
            continue;
          }
          break;
        }
        j += 1;
      }
      tokens.push({ type: 'literal', value: literal });
      i = j + 1;
      continue;
    }
    if (/[a-z_]/i.test(ch)) {
      let ident = ch;
      let j = i + 1;
      while (j < value.length && /[a-z0-9_$]/i.test(value[j]!)) {
        ident += value[j]!;
        j += 1;
      }
      const lower = ident.toLowerCase();
      tokens.push(
        BOOLEAN_KEYWORDS.has(lower)
          ? { type: 'keyword', value: lower }
          : { type: 'ident', value: lower },
      );
      i = j;
      continue;
    }
    if (/[0-9]/.test(ch) || (ch === '-' && /[0-9]/.test(value[i + 1] ?? ''))) {
      let num = ch;
      let j = i + 1;
      while (j < value.length && /[0-9.]/.test(value[j]!)) {
        num += value[j]!;
        j += 1;
      }
      tokens.push({ type: 'literal', value: num });
      i = j;
      continue;
    }
    if (ch === '(' || ch === ')' || ch === '[' || ch === ']' || ch === ',') {
      tokens.push({ type: 'punct', value: ch });
      i += 1;
      continue;
    }
    const two = value.slice(i, i + 2);
    if (two === '<>' || two === '>=' || two === '<=' || two === '!~') {
      tokens.push({ type: 'op', value: two });
      i += 2;
      continue;
    }
    if ('=<>~'.includes(ch)) {
      tokens.push({ type: 'op', value: ch });
      i += 1;
      continue;
    }
    throw new Error(`Unexpected character "${ch}" in CHECK expression`);
  }
  return tokens;
}

function peek(tokens: BooleanToken[]): BooleanToken | undefined {
  return tokens[0];
}

function consume(tokens: BooleanToken[]): BooleanToken {
  const token = tokens.shift();
  if (token === undefined) {
    throw new Error('Unexpected end of CHECK expression');
  }
  return token;
}

function expectPunct(tokens: BooleanToken[], value: string): void {
  const token = consume(tokens);
  if (token.type !== 'punct' || token.value !== value) {
    throw new Error(`Expected "${value}" but got "${token.value}"`);
  }
}

function parseBooleanExpression(tokens: BooleanToken[]): BooleanExpr {
  return parseOr(tokens);
}

function parseOr(tokens: BooleanToken[]): BooleanExpr {
  const terms: BooleanExpr[] = [parseAnd(tokens)];
  while (peek(tokens)?.type === 'keyword' && peek(tokens)?.value === 'or') {
    consume(tokens);
    terms.push(parseAnd(tokens));
  }
  if (terms.length === 1) return terms[0]!;
  return { type: 'or', terms };
}

function parseAnd(tokens: BooleanToken[]): BooleanExpr {
  const terms: BooleanExpr[] = [parseNot(tokens)];
  while (peek(tokens)?.type === 'keyword' && peek(tokens)?.value === 'and') {
    consume(tokens);
    terms.push(parseNot(tokens));
  }
  if (terms.length === 1) return terms[0]!;
  return { type: 'and', terms };
}

function parseNot(tokens: BooleanToken[]): BooleanExpr {
  if (peek(tokens)?.type === 'keyword' && peek(tokens)?.value === 'not') {
    consume(tokens);
    return { type: 'not', operand: parseNot(tokens) };
  }
  return parseComparison(tokens);
}

function parseComparison(tokens: BooleanToken[]): BooleanExpr {
  const left = parsePrimary(tokens);
  const next = peek(tokens);
  if (next?.type === 'op') {
    consume(tokens);
    const op = next.value;
    const right = parsePrimary(tokens);
    return { type: 'compare', left, op, right };
  }
  if (next?.type === 'keyword' && next.value === 'is') {
    consume(tokens);
    let not = false;
    if (peek(tokens)?.type === 'keyword' && peek(tokens)?.value === 'not') {
      consume(tokens);
      not = true;
    }
    if (peek(tokens)?.type === 'keyword' && peek(tokens)?.value === 'null') {
      consume(tokens);
      return { type: 'isnull', expr: left, not };
    }
    // Fall back to a generic IS comparison (not expected in migration 0001).
    return { type: 'compare', left, op: 'is', right: parsePrimary(tokens) };
  }
  if (next?.type === 'keyword' && next.value === 'in') {
    consume(tokens);
    expectPunct(tokens, '(');
    const values: BooleanExpr[] = [parseBooleanExpression(tokens)];
    while (peek(tokens)?.type === 'punct' && peek(tokens)?.value === ',') {
      consume(tokens);
      values.push(parseBooleanExpression(tokens));
    }
    expectPunct(tokens, ')');
    return { type: 'in', expr: left, values };
  }
  return left;
}

function parsePrimary(tokens: BooleanToken[]): BooleanExpr {
  const token = peek(tokens);
  if (token === undefined) {
    throw new Error('Unexpected end of CHECK expression');
  }
  if (token.type === 'ident') {
    consume(tokens);
    if (peek(tokens)?.type === 'punct' && peek(tokens)?.value === '(') {
      consume(tokens);
      const args: BooleanExpr[] = [];
      if (!(peek(tokens)?.type === 'punct' && peek(tokens)?.value === ')')) {
        args.push(parseBooleanExpression(tokens));
        while (peek(tokens)?.type === 'punct' && peek(tokens)?.value === ',') {
          consume(tokens);
          args.push(parseBooleanExpression(tokens));
        }
      }
      expectPunct(tokens, ')');
      return { type: 'func', name: token.value, args };
    }
    return { type: 'ident', value: token.value };
  }
  if (token.type === 'literal') {
    consume(tokens);
    return { type: 'literal', value: token.value };
  }
  if (token.type === 'keyword' && token.value === 'array') {
    consume(tokens);
    expectPunct(tokens, '[');
    const items: BooleanExpr[] = [parseBooleanExpression(tokens)];
    while (peek(tokens)?.type === 'punct' && peek(tokens)?.value === ',') {
      consume(tokens);
      items.push(parseBooleanExpression(tokens));
    }
    expectPunct(tokens, ']');
    return { type: 'array', items };
  }
  if (token.type === 'punct' && token.value === '(') {
    consume(tokens);
    const expr = parseBooleanExpression(tokens);
    expectPunct(tokens, ')');
    return expr;
  }
  throw new Error(`Unexpected token "${token.value}" in CHECK expression`);
}

function emitBooleanExpression(expr: BooleanExpr, parent: 'or' | 'and' | 'root' = 'root'): string {
  switch (expr.type) {
    case 'or': {
      const emitted = expr.terms.map((t) => emitBooleanExpression(t, 'or'));
      const str = emitted.join(' or ');
      if (parent === 'and') return `(${str})`;
      return str;
    }
    case 'and': {
      const emitted = expr.terms.map((t) => emitBooleanExpression(t, 'and'));
      const str = emitted.join(' and ');
      if (parent === 'or') return `(${str})`;
      return str;
    }
    case 'not':
      return `not ${emitBooleanExpression(expr.operand, 'root')}`;
    case 'compare': {
      const right = expr.right === null ? '' : ` ${emitBooleanExpression(expr.right, 'root')}`;
      return `${emitBooleanExpression(expr.left, 'root')} ${expr.op}${right}`;
    }
    case 'in':
      return `${emitBooleanExpression(expr.expr, 'root')} in (${expr.values
        .map((v) => emitBooleanExpression(v, 'root'))
        .join(', ')})`;
    case 'isnull':
      return `${emitBooleanExpression(expr.expr, 'root')} is ${expr.not ? 'not ' : ''}null`;
    case 'ident':
      return expr.value;
    case 'literal':
      return expr.value;
    case 'func':
      return `${expr.name}(${expr.args.map((a) => emitBooleanExpression(a, 'root')).join(', ')})`;
    case 'array':
      return `array[${expr.items.map((item) => emitBooleanExpression(item, 'root')).join(', ')}]`;
    default:
      return '';
  }
}

function normalizeBooleanExpression(definition: string): string {
  try {
    const tokens = tokenizeExpression(definition);
    const tree = parseBooleanExpression(tokens);
    if (tokens.length > 0) {
      throw new Error('Unexpected trailing tokens in CHECK expression');
    }
    return emitBooleanExpression(tree);
  } catch {
    // Fail closed by refusing to normalise an expression we cannot parse.
    return definition;
  }
}

export function normalizeCheckDefinition(definition: string): string {
  let s = collapseWhitespace(definition);
  s = s.replace(/^CHECK\s+/i, '');
  // Strip redundant keyword-quoting BEFORE lowercase so that
  // case-sensitive quoted identifiers (e.g. `"Position"`) keep their
  // quotes and remain distinguishable from bare `position` after the
  // lowercase step. See stripRedundantDoubleQuotes for the full contract.
  s = stripRedundantDoubleQuotes(s);
  s = lowercase(s);
  // PG varchar renderings must be canonicalized before stripTypeCasts turns
  // `::text[]` into a dangling `[]`.
  s = canonicalizeVarcharLiteralArray(s);
  s = canonicalizeVarcharCoalesceLiteral(s);
  s = stripCastWrap(s);
  s = stripTypeCasts(s);
  s = canonicalizeAnyArrayToIn(s);
  s = normalizeBooleanExpression(s);
  s = stripOuterParentheses(s);
  return s;
}

export function normalizeDefault(raw: string | null): string | null {
  if (raw === null) return null;
  let s = collapseWhitespace(raw);
  s = lowercase(s);
  s = stripTypeCasts(s);
  return s === '' ? null : s;
}

export function normalizeIndexDefinition(def: string): string {
  let s = collapseWhitespace(def);
  s = lowercase(s);
  s = stripPublicSchema(s);
  return s;
}

/**
 * Normalize a single index expression so the verifier collapses PG-18's
 * redundant `(col)::text` cast on bare column references into the bare
 * identifier. PG-18 `pg_get_indexdef` emits `lower((name)::text)` for a
 * declared `lower(name)` functional index, because `lower()` requires
 * `text` and PG shows the implicit cast as an explicit one. The cast AND
 * the redundant parentheses around the identifier are semantically a
 * no-op for character-typed columns; other casts (e.g. `::int`, `::bool`)
 * are preserved so the verifier stays fail-closed for genuinely
 * different expressions.
 *
 * Only the pattern `(<simple_identifier>)::text` is collapsed; any other
 * shape (function call with multiple args, array casts, arithmetic) is
 * returned unchanged. The function is intentionally narrow: equivalence
 * is claimed ONLY for the `(col)::text` -> `col` case (no parentheses,
 * no cast).
 *
 * One further PG-rendered variant is canonicalized: for a varchar column,
 * `lower(COALESCE(col, ''))` is emitted as
 * `lower((coalesce(col, ''::character varying))::text)`; see
 * `canonicalizeVarcharCoalesceLiteral` for the exact, narrow contract.
 */
export function normalizeIndexExpression(expression: string): string {
  return canonicalizeVarcharCoalesceLiteral(expression).replace(
    /\(\s*([a-zA-Z_][a-zA-Z0-9_]*)\s*\)::text\b/g,
    '$1',
  );
}

